/// The colour of an AutoCAD colour index (1–255) in AutoCAD's standard palette.
pub fn aci_rgb(index: u8) -> [u8; 3] {
    match index {
        1 => [255, 0, 0],
        2 => [255, 255, 0],
        3 => [0, 255, 0],
        4 => [0, 255, 255],
        5 => [0, 0, 255],
        6 => [255, 0, 255],
        7 => [255, 255, 255],
        8 => [128, 128, 128],
        9 => [192, 192, 192],
        10..=249 => {
            // 24 hues 15° apart, each in 5 shades, each shade full and half saturated.
            let hue = f64::from((index - 10) / 10) * 15.0;
            let shade = [255.0, 165.0, 127.0, 76.0, 38.0][usize::from((index % 10) / 2)];
            let pale = index % 2 == 1;
            let channel = |offset: f64| {
                let distance = ((hue - offset).rem_euclid(360.0)).min((offset - hue).rem_euclid(360.0));
                let level = (2.0 - distance / 60.0).clamp(0.0, 1.0);
                let level = if pale { (1.0 + level) / 2.0 } else { level };
                (shade * level).floor() as u8
            };
            [channel(0.0), channel(120.0), channel(240.0)]
        }
        250..=255 => {
            let grey = [51, 80, 105, 130, 190, 255][usize::from(index - 250)];
            [grey; 3]
        }
        0 => [0, 0, 0],
    }
}

/// The AutoCAD colour index closest to a colour, leaving out 7, which AutoCAD draws black or white to suit the
/// background.
pub fn nearest_aci(rgb: [u8; 3]) -> u8 {
    let distance = |index: u8| {
        let other = aci_rgb(index);
        (0..3)
            .map(|channel| (i32::from(rgb[channel]) - i32::from(other[channel])).pow(2))
            .sum::<i32>()
    };
    (1..=255u8)
        .filter(|&index| index != 7)
        .min_by_key(|&index| distance(index))
        .unwrap()
}

/// How a colour is written to DXF: a colour index, and the true colour (`0x00RRGGBB`) unless the colour is black or
/// white. Those take index 7, which AutoCAD draws black on a light background and white on a dark one, so they never
/// vanish into the background. NetCAD draws on black, and some layers are stored as `00 00 01`.
pub fn dxf_color(rgb: [u8; 3]) -> (u8, Option<i32>) {
    let [red, green, blue] = rgb;
    let (low, high) = (red.min(green).min(blue), red.max(green).max(blue));
    if high <= 8 || low >= 247 {
        return (7, None);
    }
    let true_color = i32::from(red) << 16 | i32::from(green) << 8 | i32::from(blue);
    (nearest_aci(rgb), Some(true_color))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn aci_palette() {
        // Values from AutoCAD's palette.
        assert_eq!(aci_rgb(10), [255, 0, 0]);
        assert_eq!(aci_rgb(11), [255, 127, 127]);
        assert_eq!(aci_rgb(13), [165, 82, 82]);
        assert_eq!(aci_rgb(20), [255, 63, 0]);
        assert_eq!(aci_rgb(21), [255, 159, 127]);
        assert_eq!(aci_rgb(30), [255, 127, 0]);
        assert_eq!(aci_rgb(40), [255, 191, 0]);
        assert_eq!(aci_rgb(130), [0, 255, 255]);
        assert_eq!(aci_rgb(170), [0, 0, 255]);
        assert_eq!(aci_rgb(171), [127, 127, 255]);
        assert_eq!(aci_rgb(250), [51, 51, 51]);
    }

    #[test]
    fn netcad_colors() {
        // NetCAD's 1 is blue, AutoCAD's 5.
        assert_eq!(dxf_color(DEFAULT_PALETTE[1].unwrap()), (5, Some(0x0000ff)));
        assert_eq!(dxf_color(DEFAULT_PALETTE[4].unwrap()), (1, Some(0xff0000)));
        assert_eq!(dxf_color(DEFAULT_PALETTE[14].unwrap()), (2, Some(0xffff00)));
        assert_eq!(dxf_color(DEFAULT_PALETTE[5].unwrap()).0, 30);
        // Black and white suit the background.
        assert_eq!(dxf_color([0, 0, 1]), (7, None));
        assert_eq!(dxf_color([255, 255, 255]), (7, None));
    }
}
